// verdict (unresolvable registry metadata in the sandboxed research
// environment) — not added. See 02-RESEARCH.md Package Legitimacy Audit.
//
// Path data provenance (copied verbatim — never freehand-traced):
//   - FacebookIcon, InstagramIcon: Simple Icons (https://simple-icons.org),
//     CC0-licensed canonical monochrome brand marks, native 24x24 viewBox —
//     used as-is, no transform needed.
//   - LinkedinIcon: Font Awesome Free's `linkedin-in` glyph
//     (https://fontawesome.com/icons/linkedin-in?style=brands), native
//     viewBox "0 0 448 512". The path data is copied byte-for-byte,
//     unmodified, and wrapped in a <g transform="scale(...)"> (plus a small
//     centering translate) that normalizes it into this file's shared
//     24x24 viewBox so all three icons share one call-site contract. This
//     satisfies the project's prohibition on freehand-traced brand marks —
//     the path itself is never redrawn, only repositioned via SVG transform.
// Sourced 2026-08-16.

